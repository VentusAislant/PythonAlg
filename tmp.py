class ScoreSystem:
    def __init__(self, data: str):
        self.records = self._parse_data(data)
        self._build_ranking()
        self._build_index()

    # ========= 数据解析 =========
    def _parse_data(self, data: str):
        lines = data.strip().split("\n")
        records = []

        for line in lines[1:]:  # 跳过表头
            parts = line.split()

            record = {
                "序号": int(parts[0]),
                "报名号": parts[1],
                "姓名": parts[2],
                "导师": parts[3],
                "面试": float(parts[-2]),
                "总分": float(parts[-1]),
            }
            records.append(record)

        return records

    # ========= 排名 =========
    def _build_ranking(self):
        self.records.sort(key=lambda x: x["总分"], reverse=True)

        rank = 1
        for i, rec in enumerate(self.records):
            if i > 0 and rec["总分"] < self.records[i - 1]["总分"]:
                rank = i + 1
            rec["排名"] = rank

    # ========= 建立索引 =========
    def _build_index(self):
        self.name_index = {}
        self.id_index = {}

        for rec in self.records:
            self.name_index[rec["姓名"]] = rec
            self.id_index[rec["报名号"]] = rec

    # ========= 查询 =========
    def query(self, key: str):
        if key in self.name_index:
            rec = self.name_index[key]
        elif key in self.id_index:
            rec = self.id_index[key]
        else:
            return "未找到该用户"

        return self._format_output(rec)

    # ========= 模糊查询 =========
    def fuzzy_query(self, keyword: str):
        return [
            self._format_output(r)
            for r in self.records
            if keyword in r["姓名"] or keyword in r["报名号"]
        ]

    # ========= 查询某导师 =========
    def query_by_teacher(self, teacher: str):
        return [
            self._format_output(r)
            for r in self.records
            if r["导师"] == teacher
        ]

    # ========= Top K =========
    def top_k(self, k=5):
        return [self._format_output(r) for r in self.records[:k]]

    # ========= 格式化输出 =========
    def _format_output(self, rec):
        return {
            "姓名": rec["姓名"],
            "报名号": rec["报名号"],
            "导师": rec["导师"],
            "面试成绩": rec["面试"],
            "总分": rec["总分"],
            "排名": rec["排名"],
        }

